-- -----------------------------------------------------------------------------
-- VIEW 1: VW_MONTHLY_FINANCIAL_SUMMARY
-- Aggregates monthly income, gross expenses, refunds offset, net expenses,
-- and personal savings metrics.
-- -----------------------------------------------------------------------------
CREATE OR REPLACE VIEW VW_MONTHLY_FINANCIAL_SUMMARY AS
SELECT
    EXTRACT(YEAR FROM t.TRANSACTION_DATE) AS REPORT_YEAR,
    EXTRACT(MONTH FROM t.TRANSACTION_DATE) AS REPORT_MONTH,
    TO_CHAR(t.TRANSACTION_DATE, 'Mon YYYY') AS MONTH_LABEL,
    SUM(CASE WHEN t.TRANSACTION_TYPE = 'INCOME' THEN t.AMOUNT ELSE 0 END) AS TOTAL_INCOME,
    SUM(CASE WHEN t.TRANSACTION_TYPE = 'EXPENSE' THEN t.AMOUNT ELSE 0 END) AS GROSS_EXPENSES,
    SUM(CASE WHEN t.TRANSACTION_TYPE = 'REFUND' THEN t.AMOUNT ELSE 0 END) AS TOTAL_REFUNDS,
    (SUM(CASE WHEN t.TRANSACTION_TYPE = 'EXPENSE' THEN t.AMOUNT ELSE 0 END) -
     SUM(CASE WHEN t.TRANSACTION_TYPE = 'REFUND' THEN t.AMOUNT ELSE 0 END)) AS NET_EXPENSES,
    (SUM(CASE WHEN t.TRANSACTION_TYPE = 'INCOME' THEN t.AMOUNT ELSE 0 END) -
     (SUM(CASE WHEN t.TRANSACTION_TYPE = 'EXPENSE' THEN t.AMOUNT ELSE 0 END) -
      SUM(CASE WHEN t.TRANSACTION_TYPE = 'REFUND' THEN t.AMOUNT ELSE 0 END))) AS NET_SAVINGS,
    ROUND(
        (SUM(CASE WHEN t.TRANSACTION_TYPE = 'INCOME' THEN t.AMOUNT ELSE 0 END) -
         (SUM(CASE WHEN t.TRANSACTION_TYPE = 'EXPENSE' THEN t.AMOUNT ELSE 0 END) -
          SUM(CASE WHEN t.TRANSACTION_TYPE = 'REFUND' THEN t.AMOUNT ELSE 0 END))) /
        NULLIF(SUM(CASE WHEN t.TRANSACTION_TYPE = 'INCOME' THEN t.AMOUNT ELSE 0 END), 0) * 100, 2
    ) AS SAVINGS_RATE_PCT,
    COUNT(t.TRANSACTION_ID) AS TRANSACTION_COUNT
FROM TRANSACTIONS t
GROUP BY EXTRACT(YEAR FROM t.TRANSACTION_DATE),
         EXTRACT(MONTH FROM t.TRANSACTION_DATE),
         TO_CHAR(t.TRANSACTION_DATE, 'Mon YYYY');

COMMENT ON TABLE VW_MONTHLY_FINANCIAL_SUMMARY IS 'High-level executive financial metrics per calendar month.';

-- -----------------------------------------------------------------------------
-- VIEW 2: VW_CATEGORY_SPEND_ANALYSIS
-- Breakdown of category spending, refunds, and percentage of monthly outlay.
-- -----------------------------------------------------------------------------
CREATE OR REPLACE VIEW VW_CATEGORY_SPEND_ANALYSIS AS
WITH MonthlyCatSpend AS (
    SELECT
        EXTRACT(YEAR FROM t.TRANSACTION_DATE) AS TXN_YEAR,
        EXTRACT(MONTH FROM t.TRANSACTION_DATE) AS TXN_MONTH,
        c.CATEGORY_ID,
        c.CATEGORY_NAME,
        c.CATEGORY_TYPE,
        SUM(CASE WHEN t.TRANSACTION_TYPE = 'EXPENSE' THEN t.AMOUNT ELSE 0 END) AS GROSS_SPEND,
        SUM(CASE WHEN t.TRANSACTION_TYPE = 'REFUND' THEN t.AMOUNT ELSE 0 END) AS REFUNDS,
        (SUM(CASE WHEN t.TRANSACTION_TYPE = 'EXPENSE' THEN t.AMOUNT ELSE 0 END) -
         SUM(CASE WHEN t.TRANSACTION_TYPE = 'REFUND' THEN t.AMOUNT ELSE 0 END)) AS NET_SPEND,
        COUNT(t.TRANSACTION_ID) AS TXN_COUNT
    FROM TRANSACTIONS t
    JOIN CATEGORIES c ON t.CATEGORY_ID = c.CATEGORY_ID
    WHERE t.TRANSACTION_TYPE IN ('EXPENSE', 'REFUND')
    GROUP BY EXTRACT(YEAR FROM t.TRANSACTION_DATE),
             EXTRACT(MONTH FROM t.TRANSACTION_DATE),
             c.CATEGORY_ID, c.CATEGORY_NAME, c.CATEGORY_TYPE
)
SELECT
    TXN_YEAR,
    TXN_MONTH,
    CATEGORY_ID,
    CATEGORY_NAME,
    CATEGORY_TYPE,
    GROSS_SPEND,
    REFUNDS,
    NET_SPEND,
    ROUND(NET_SPEND / NULLIF(SUM(NET_SPEND) OVER (PARTITION BY TXN_YEAR, TXN_MONTH), 0) * 100, 2) AS SPEND_SHARE_PCT,
    TXN_COUNT,
    DENSE_RANK() OVER (PARTITION BY TXN_YEAR, TXN_MONTH ORDER BY NET_SPEND DESC) AS MONTHLY_SPEND_RANK
FROM MonthlyCatSpend;

COMMENT ON TABLE VW_CATEGORY_SPEND_ANALYSIS IS 'Detailed category spending with net calculations and monthly ranks.';

-- -----------------------------------------------------------------------------
-- VIEW 3: VW_BUDGET_UTILIZATION
-- Compares allocated monthly budget to actual net spending, detects overruns.
-- -----------------------------------------------------------------------------
CREATE OR REPLACE VIEW VW_BUDGET_UTILIZATION AS
SELECT
    b.BUDGET_ID,
    b.BUDGET_YEAR,
    b.BUDGET_MONTH,
    c.CATEGORY_ID,
    c.CATEGORY_NAME,
    b.BUDGET_AMOUNT,
    NVL(act.NET_SPEND, 0) AS ACTUAL_NET_SPEND,
    (b.BUDGET_AMOUNT - NVL(act.NET_SPEND, 0)) AS BUDGET_VARIANCE,
    ROUND(NVL(act.NET_SPEND, 0) / NULLIF(b.BUDGET_AMOUNT, 0) * 100, 2) AS UTILIZATION_PCT,
    CASE
        WHEN NVL(act.NET_SPEND, 0) > b.BUDGET_AMOUNT THEN 'BREACH'
        WHEN (NVL(act.NET_SPEND, 0) / NULLIF(b.BUDGET_AMOUNT, 0)) >= 0.85 THEN 'WARNING'
        ELSE 'ON_TRACK'
    END AS BUDGET_STATUS
FROM MONTHLY_BUDGET b
JOIN CATEGORIES c ON b.CATEGORY_ID = c.CATEGORY_ID
LEFT JOIN (
    SELECT
        EXTRACT(YEAR FROM t.TRANSACTION_DATE) AS T_YEAR,
        EXTRACT(MONTH FROM t.TRANSACTION_DATE) AS T_MONTH,
        t.CATEGORY_ID,
        (SUM(CASE WHEN t.TRANSACTION_TYPE = 'EXPENSE' THEN t.AMOUNT ELSE 0 END) -
         SUM(CASE WHEN t.TRANSACTION_TYPE = 'REFUND' THEN t.AMOUNT ELSE 0 END)) AS NET_SPEND
    FROM TRANSACTIONS t
    WHERE t.TRANSACTION_TYPE IN ('EXPENSE', 'REFUND')
    GROUP BY EXTRACT(YEAR FROM t.TRANSACTION_DATE), EXTRACT(MONTH FROM t.TRANSACTION_DATE), t.CATEGORY_ID
) act ON b.BUDGET_YEAR = act.T_YEAR
     AND b.BUDGET_MONTH = act.T_MONTH
     AND b.CATEGORY_ID = act.CATEGORY_ID;

COMMENT ON TABLE VW_BUDGET_UTILIZATION IS 'Budget tracking view comparing budgeted limits to net actual expenditures.';

-- -----------------------------------------------------------------------------
-- VIEW 4: VW_PAYMENT_METHOD_METRICS
-- Analyzes transaction channel preferences and ticketing volume.
-- -----------------------------------------------------------------------------
CREATE OR REPLACE VIEW VW_PAYMENT_METHOD_METRICS AS
SELECT
    t.PAYMENT_METHOD,
    COUNT(t.TRANSACTION_ID) AS TRANSACTION_COUNT,
    SUM(CASE WHEN t.TRANSACTION_TYPE = 'EXPENSE' THEN t.AMOUNT ELSE 0 END) AS TOTAL_EXPENSE_VOLUME,
    ROUND(AVG(CASE WHEN t.TRANSACTION_TYPE = 'EXPENSE' THEN t.AMOUNT ELSE NULL END), 2) AS AVG_EXPENSE_AMOUNT,
    SUM(CASE WHEN t.TRANSACTION_TYPE = 'INCOME' THEN t.AMOUNT ELSE 0 END) AS TOTAL_INCOME_VOLUME,
    SUM(CASE WHEN t.TRANSACTION_TYPE = 'REFUND' THEN t.AMOUNT ELSE 0 END) AS TOTAL_REFUND_VOLUME
FROM TRANSACTIONS t
GROUP BY t.PAYMENT_METHOD;

