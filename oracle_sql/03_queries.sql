SET PAGESIZE 50;
SET LINESIZE 200;
SET FEEDBACK ON;

-- -----------------------------------------------------------------------------
-- QUERY 1: MONTHLY FINANCIAL RECONCILIATION SUMMARY
-- Computes total income, gross expenditure, refunds offset, net expense,
-- and net savings surplus per calendar month.
-- -----------------------------------------------------------------------------
PROMPT --- [QUERY 1] MONTHLY FINANCIAL RECONCILIATION ---;
SELECT
    TO_CHAR(t.TRANSACTION_DATE, 'YYYY-MM') AS REPORT_MONTH,
    SUM(CASE WHEN t.TRANSACTION_TYPE = 'INCOME' THEN t.AMOUNT ELSE 0 END) AS TOTAL_INCOME,
    SUM(CASE WHEN t.TRANSACTION_TYPE = 'EXPENSE' THEN t.AMOUNT ELSE 0 END) AS GROSS_EXPENSES,
    SUM(CASE WHEN t.TRANSACTION_TYPE = 'REFUND' THEN t.AMOUNT ELSE 0 END) AS TOTAL_REFUNDS,
    (SUM(CASE WHEN t.TRANSACTION_TYPE = 'EXPENSE' THEN t.AMOUNT ELSE 0 END) -
     SUM(CASE WHEN t.TRANSACTION_TYPE = 'REFUND' THEN t.AMOUNT ELSE 0 END)) AS NET_EXPENSES,
    (SUM(CASE WHEN t.TRANSACTION_TYPE = 'INCOME' THEN t.AMOUNT ELSE 0 END) -
     (SUM(CASE WHEN t.TRANSACTION_TYPE = 'EXPENSE' THEN t.AMOUNT ELSE 0 END) -
      SUM(CASE WHEN t.TRANSACTION_TYPE = 'REFUND' THEN t.AMOUNT ELSE 0 END))) AS NET_SAVINGS,
    ROUND(
        (SUM(CASE WHEN t.TRANSACTION_TYPE = 'INCOME' THEN t.AMOUNT ELSE 0 END) -
         (SUM(CASE WHEN t.TRANSACTION_TYPE = 'EXPENSE' THEN t.AMOUNT ELSE 0 END) -
          SUM(CASE WHEN t.TRANSACTION_TYPE = 'REFUND' THEN t.AMOUNT ELSE 0 END))) /
        NULLIF(SUM(CASE WHEN t.TRANSACTION_TYPE = 'INCOME' THEN t.AMOUNT ELSE 0 END), 0) * 100, 2
    ) AS SAVINGS_RATE_PCT,
    COUNT(t.TRANSACTION_ID) AS TRANSACTION_COUNT
FROM TRANSACTIONS t
GROUP BY TO_CHAR(t.TRANSACTION_DATE, 'YYYY-MM')
ORDER BY REPORT_MONTH;

-- -----------------------------------------------------------------------------
-- QUERY 2: CATEGORY-WISE NET SPENDING & PERCENTAGE SHARE
-- Isolates pure expenditures (excluding income) and accounts for refunds.
-- -----------------------------------------------------------------------------
PROMPT --- [QUERY 2] CATEGORY-WISE SPEND DISTRIBUTION & SHARE ---;
WITH CatTotals AS (
    SELECT
        c.CATEGORY_NAME,
        SUM(CASE WHEN t.TRANSACTION_TYPE = 'EXPENSE' THEN t.AMOUNT ELSE 0 END) AS GROSS_SPEND,
        SUM(CASE WHEN t.TRANSACTION_TYPE = 'REFUND' THEN t.AMOUNT ELSE 0 END) AS REFUNDS,
        (SUM(CASE WHEN t.TRANSACTION_TYPE = 'EXPENSE' THEN t.AMOUNT ELSE 0 END) -
         SUM(CASE WHEN t.TRANSACTION_TYPE = 'REFUND' THEN t.AMOUNT ELSE 0 END)) AS NET_SPEND,
        COUNT(t.TRANSACTION_ID) AS TXN_COUNT
    FROM TRANSACTIONS t
    JOIN CATEGORIES c ON t.CATEGORY_ID = c.CATEGORY_ID
    WHERE t.TRANSACTION_TYPE IN ('EXPENSE', 'REFUND')
    GROUP BY c.CATEGORY_NAME
)
SELECT
    CATEGORY_NAME,
    GROSS_SPEND,
    REFUNDS,
    NET_SPEND,
    ROUND(NET_SPEND / NULLIF(SUM(NET_SPEND) OVER(), 0) * 100, 2) AS SPEND_SHARE_PCT,
    TXN_COUNT,
    DENSE_RANK() OVER (ORDER BY NET_SPEND DESC) AS SPEND_RANK
FROM CatTotals
ORDER BY NET_SPEND DESC;

-- -----------------------------------------------------------------------------
-- QUERY 3: BUDGET VS ACTUAL SPENDING VARIANCE & UTILIZATION %
-- Computes variance and utilization for each budgeted category by month.
-- -----------------------------------------------------------------------------
PROMPT --- [QUERY 3] BUDGET VS ACTUAL VARIANCE & BREACH IDENTIFICATION ---;
SELECT
    b.BUDGET_YEAR,
    b.BUDGET_MONTH,
    c.CATEGORY_NAME,
    b.BUDGET_AMOUNT,
    NVL(actual.GROSS_SPEND, 0) AS GROSS_SPEND,
    NVL(actual.REFUNDS, 0) AS REFUNDS,
    NVL(actual.NET_SPEND, 0) AS ACTUAL_NET_SPEND,
    (b.BUDGET_AMOUNT - NVL(actual.NET_SPEND, 0)) AS BUDGET_VARIANCE,
    ROUND(NVL(actual.NET_SPEND, 0) / NULLIF(b.BUDGET_AMOUNT, 0) * 100, 2) AS UTILIZATION_PCT,
    CASE
        WHEN NVL(actual.NET_SPEND, 0) > b.BUDGET_AMOUNT THEN 'BREACH'
        WHEN (NVL(actual.NET_SPEND, 0) / NULLIF(b.BUDGET_AMOUNT, 0)) >= 0.85 THEN 'WARNING'
        ELSE 'ON_TRACK'
    END AS BUDGET_STATUS
FROM MONTHLY_BUDGET b
JOIN CATEGORIES c ON b.CATEGORY_ID = c.CATEGORY_ID
LEFT JOIN (
    SELECT
        EXTRACT(YEAR FROM t.TRANSACTION_DATE) AS T_YEAR,
        EXTRACT(MONTH FROM t.TRANSACTION_DATE) AS T_MONTH,
        t.CATEGORY_ID,
        SUM(CASE WHEN t.TRANSACTION_TYPE = 'EXPENSE' THEN t.AMOUNT ELSE 0 END) AS GROSS_SPEND,
        SUM(CASE WHEN t.TRANSACTION_TYPE = 'REFUND' THEN t.AMOUNT ELSE 0 END) AS REFUNDS,
        (SUM(CASE WHEN t.TRANSACTION_TYPE = 'EXPENSE' THEN t.AMOUNT ELSE 0 END) -
         SUM(CASE WHEN t.TRANSACTION_TYPE = 'REFUND' THEN t.AMOUNT ELSE 0 END)) AS NET_SPEND
    FROM TRANSACTIONS t
    WHERE t.TRANSACTION_TYPE IN ('EXPENSE', 'REFUND')
    GROUP BY EXTRACT(YEAR FROM t.TRANSACTION_DATE), EXTRACT(MONTH FROM t.TRANSACTION_DATE), t.CATEGORY_ID
) actual ON b.BUDGET_YEAR = actual.T_YEAR
        AND b.BUDGET_MONTH = actual.T_MONTH
        AND b.CATEGORY_ID = actual.CATEGORY_ID
ORDER BY b.BUDGET_YEAR, b.BUDGET_MONTH, ACTUAL_NET_SPEND DESC;

-- -----------------------------------------------------------------------------
-- QUERY 4: MONTH-OVER-MONTH (MoM) EXPENDITURE GROWTH (WINDOW FUNCTION)
-- Uses analytic LAG() function to compute month-to-month change in net expenses.
-- -----------------------------------------------------------------------------
PROMPT --- [QUERY 4] MONTH-OVER-MONTH EXPENDITURE GROWTH TREND ---;
WITH MonthlyNet AS (
    SELECT
        EXTRACT(YEAR FROM TRANSACTION_DATE) AS T_YEAR,
        EXTRACT(MONTH FROM TRANSACTION_DATE) AS T_MONTH,
        TO_CHAR(TRANSACTION_DATE, 'Mon YYYY') AS MONTH_LABEL,
        (SUM(CASE WHEN TRANSACTION_TYPE = 'EXPENSE' THEN AMOUNT ELSE 0 END) -
         SUM(CASE WHEN TRANSACTION_TYPE = 'REFUND' THEN AMOUNT ELSE 0 END)) AS NET_EXPENSES
    FROM TRANSACTIONS
    WHERE TRANSACTION_TYPE IN ('EXPENSE', 'REFUND')
    GROUP BY EXTRACT(YEAR FROM TRANSACTION_DATE), EXTRACT(MONTH FROM TRANSACTION_DATE), TO_CHAR(TRANSACTION_DATE, 'Mon YYYY')
)
SELECT
    T_YEAR,
    T_MONTH,
    MONTH_LABEL,
    NET_EXPENSES,
    LAG(NET_EXPENSES, 1) OVER (ORDER BY T_YEAR, T_MONTH) AS PRIOR_MONTH_EXPENSES,
    (NET_EXPENSES - LAG(NET_EXPENSES, 1) OVER (ORDER BY T_YEAR, T_MONTH)) AS MOM_NET_CHANGE,
    ROUND(
        (NET_EXPENSES - LAG(NET_EXPENSES, 1) OVER (ORDER BY T_YEAR, T_MONTH)) /
        NULLIF(LAG(NET_EXPENSES, 1) OVER (ORDER BY T_YEAR, T_MONTH), 0) * 100, 2
    ) AS MOM_GROWTH_PCT
FROM MonthlyNet
ORDER BY T_YEAR, T_MONTH;

-- -----------------------------------------------------------------------------
-- QUERY 5: PAYMENT METHOD VOLUME & UTILIZATION ANALYSIS
-- -----------------------------------------------------------------------------
PROMPT --- [QUERY 5] PAYMENT CHANNEL VOLUMES & AVERAGE TICKET SIZE ---;
SELECT
    PAYMENT_METHOD,
    COUNT(TRANSACTION_ID) AS TOTAL_TXNS,
    SUM(CASE WHEN TRANSACTION_TYPE = 'EXPENSE' THEN AMOUNT ELSE 0 END) AS TOTAL_DEBIT_VOLUME,
    ROUND(AVG(CASE WHEN TRANSACTION_TYPE = 'EXPENSE' THEN AMOUNT ELSE NULL END), 2) AS AVG_TICKET_SIZE,
    ROUND(
        SUM(CASE WHEN TRANSACTION_TYPE = 'EXPENSE' THEN AMOUNT ELSE 0 END) /
        NULLIF(SUM(SUM(CASE WHEN TRANSACTION_TYPE = 'EXPENSE' THEN AMOUNT ELSE 0 END)) OVER(), 0) * 100, 2
    ) AS CHANNEL_SHARE_PCT
FROM TRANSACTIONS
GROUP BY PAYMENT_METHOD
ORDER BY TOTAL_DEBIT_VOLUME DESC;

-- -----------------------------------------------------------------------------
-- QUERY 6: UNCATEGORISED TRANSACTIONS MONITORING
-- Identifies transactions that could not be auto-categorized.
-- -----------------------------------------------------------------------------
PROMPT --- [QUERY 6] AUDIT OF UNCATEGORISED TRANSACTIONS ---;
SELECT
    t.TRANSACTION_ID,
    TO_CHAR(t.TRANSACTION_DATE, 'YYYY-MM-DD') AS TXN_DATE,
    t.DESCRIPTION,
    t.AMOUNT,
    t.PAYMENT_METHOD,
    t.NOTES
FROM TRANSACTIONS t
JOIN CATEGORIES c ON t.CATEGORY_ID = c.CATEGORY_ID
WHERE c.CATEGORY_NAME = 'Uncategorised'
ORDER BY t.TRANSACTION_DATE DESC;
